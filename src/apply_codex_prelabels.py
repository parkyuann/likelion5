def provisional_source_scope(row: pd.Series, claim_class: str) -> str:
    """문장만으로 확정하지 못하는 출처 범위는 명시적으로 검토 대기로 둔다."""
    source = str(row.get("source_org_raw") or "")
    if not source or source.lower() == "nan":
        return "불명"
    if any(name in source for name in ("통계청", "국가데이터처")):
        return "KOSIS계열"
    if any(
        name in source
        for name in (
            "한국은행", "관세청", "국세청", "기상청", "금융감독원",
            "공정거래위원회", "산업통상자원부", "농림축산식품부",
            "한국석유공사", "한국거래소", "국민연금공단",
        )
    ):
        return "타공식기관"
    if any(name in source for name in ("미 노동부", "미국", "CDC", "연준")):
        return "해외기관"
    return "불명"


def prelabel_candidates(input_name: str, output_name: str, classes: dict[str, str]) -> None:
    frame = pd.read_csv(LABEL_DIR / input_name)
    if set(frame["sample_id"]) != set(classes):
        missing = set(frame["sample_id"]) - set(classes)
        extra = set(classes) - set(frame["sample_id"])
        raise ValueError(f"라벨 매핑 불일치 missing={missing}, extra={extra}")

    frame["gold_claim_class"] = frame["sample_id"].map(classes)
    frame["gold_is_aggregate_claim"] = frame["gold_claim_class"].eq("집계통계")
    frame["gold_source_scope"] = frame.apply(
        lambda row: provisional_source_scope(row, row["gold_claim_class"]), axis=1
    )
    frame["gold_verifiability_prefilter"] = frame.apply(
        lambda row: (
            "검증시도" if row["gold_is_aggregate_claim"] and row["gold_source_scope"] == "KOSIS계열"
            else "판단불가(범위밖)"
        ),
        axis=1,
    )
    frame["gold_value"] = frame["value_list"]
    frame["gold_unit"] = frame["unit_list"]
    frame["gold_time_ref"] = frame["time_ref"]
    frame["gold_time_compare"] = frame["time_compare"]
    frame["gold_source_org_raw"] = frame["source_org_raw"]
    frame["gold_notes"] = frame.apply(
        lambda row: f"Codex 실버 라벨: {row['gold_claim_class']}; 사람/Claude 검토 필요",
        axis=1,
    )
    frame["annotator"] = "codex_prelabel"
    frame["codex_prelabel"] = True
    frame["human_review_status"] = "pending"
    frame["human_corrected"] = ""
    frame["human_review_notes"] = ""
    frame["reviewer"] = ""
    frame.to_csv(LABEL_DIR / output_name, index=False, encoding="utf-8-sig")


def normalize_article_scope(scope_hint: str) -> str:
    """기사 메모용 세부 출처 힌트를 현재 스키마의 5개 값으로 접는다."""
    if "KOSIS" in scope_hint:
        return "KOSIS계열"
    if scope_hint.startswith("해외"):
        return "해외기관"
    if scope_hint in {"공공기관통계", "공공기관집계", "공공기관연구", "공공기관시장통계"}:
        return "타공식기관"
    if scope_hint:
        return "민간기관"
    return "불명"


def closest_evidence(body: str, normalized_claim: str) -> str:
    """정규화 주장과 가장 가까운 원문 문장을 찾아 직접 인용으로 저장한다."""
    sentences = [part.strip() for part in re.split(r"(?<=[.!?。])\s+|(?<=다\.)", body) if part.strip()]
    if not sentences:
        return body.strip()
    return max(
        sentences,
        key=lambda sentence: SequenceMatcher(None, normalized_claim, sentence).ratio(),
    )


def prelabel_articles(
    input_name: str,
    output_name: str,
    annotations: dict[str, list[tuple[str, str, str]]],
) -> None:
    frame = pd.read_csv(LABEL_DIR / input_name)
    unknown = set(annotations) - set(frame["sample_id"])
    if unknown:
        raise ValueError(f"기사 라벨 매핑에 표본 밖 ID가 있음: {unknown}")

    def claims_for(row: pd.Series) -> list[dict[str, str]]:
        claims = []
        for text, scope_hint, source_org in annotations.get(row["sample_id"], []):
            claims.append(
                {
                    "claim_text": text,
                    "evidence_quote": closest_evidence(str(row["본문_정제"]), text),
                    "claim_class": "집계통계",
                    "indicator_raw": "",
                    "population": "",
                    "value": "",
                    "unit": "",
                    "time_ref": "",
                    "time_compare": "",
                    "source_scope": normalize_article_scope(scope_hint),
                    "source_org_raw": source_org,
                    "source_scope_detail": scope_hint,
                }
            )
        return claims

    claim_lists = frame.apply(claims_for, axis=1)
    frame["gold_annotation_complete"] = True
    frame["gold_claim_count"] = claim_lists.map(len)
    frame["gold_claims_json"] = claim_lists.map(
        lambda claims: json.dumps(claims, ensure_ascii=False)
    )
    frame["gold_notes"] = frame["gold_claim_count"].map(
        lambda count: (
            f"Codex 기사 전체 실버 라벨: 집계통계 주장 {count}건; 사람/Claude 검토 필요"
        )
    )
    frame["annotator"] = "codex_prelabel"
    frame["codex_prelabel"] = True
    frame["human_review_status"] = "pending"
    frame["human_corrected"] = ""
    frame["human_review_notes"] = ""
    frame["reviewer"] = ""
    frame.to_csv(LABEL_DIR / output_name, index=False, encoding="utf-8-sig")


